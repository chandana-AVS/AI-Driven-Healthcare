const SPEECH_LANG = { en: 'en-IN', te: 'te-IN', hi: 'hi-IN', ta: 'ta-IN', kn: 'kn-IN', ml: 'ml-IN' }

function findVoice(language) {
  if (typeof window === 'undefined' || !window.speechSynthesis) return null
  const voices = window.speechSynthesis.getVoices()
  return voices.find((v) => v.lang === SPEECH_LANG[language]) || voices.find((v) => v.lang?.toLowerCase().startsWith(language)) || null
}

/** Copy, print and read-aloud buttons for a translated result. */
export function ResultActions({ text, language }) {
  const [copied, setCopied] = useState(false)
  const [speaking, setSpeaking] = useState(false)
  const [voice, setVoice] = useState(() => findVoice(language))

  useEffect(() => {
    const synth = window.speechSynthesis
    if (!synth) return undefined
    const update = () => setVoice(findVoice(language))
    update()
    synth.addEventListener?.('voiceschanged', update)
    return () => { synth.removeEventListener?.('voiceschanged', update); synth.cancel() }
  }, [language])

  const copy = async () => {
    try { await navigator.clipboard.writeText(text); setCopied(true); setTimeout(() => setCopied(false), 2000) } catch { /* clipboard blocked */ }
  }
  const speak = () => {
    const synth = window.speechSynthesis
    if (speaking) { synth.cancel(); setSpeaking(false); return }
    const u = new SpeechSynthesisUtterance(text)
    u.voice = voice
    u.lang = voice?.lang || SPEECH_LANG[language] || language
    u.rate = 0.9
    u.onend = u.onerror = () => setSpeaking(false)
    synth.cancel(); synth.speak(u); setSpeaking(true)
  }

  return (
    <div className="no-print flex flex-wrap gap-2">
      <button type="button" className="btn-secondary px-3 py-2 text-sm" onClick={copy}>
        {copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" />}{copied ? 'Copied' : 'Copy'}
      </button>
      <button type="button" className="btn-secondary px-3 py-2 text-sm" onClick={() => window.print()}>
        <Printer className="h-4 w-4" />Print
      </button>
      {typeof window !== 'undefined' && window.speechSynthesis && (
        <button type="button" className="btn-secondary px-3 py-2 text-sm" onClick={speak} disabled={!voice}
          title={voice ? 'Read the translation aloud' : `This device has no ${languageLabel(language)} voice installed`}>
          {speaking ? <Square className="h-4 w-4" /> : <Volume2 className="h-4 w-4" />}{speaking ? 'Stop' : 'Listen'}
        </button>
      )}
    </div>
  )
}

/** Chips for every language this document has already been translated into. */
export function SavedTranslations({ items, current, onSelect }) {
  const done = (items || []).filter((a) => a.status === 'COMPLETED')
  if (!done.length) return null
  return (
    <div className="no-print flex flex-wrap items-center gap-2 text-sm">
      <span className="flex items-center gap-1 font-medium text-slate-600"><Languages className="h-4 w-4" />Saved translations:</span>
      {done.map((a) => (
        <button key={a.language_code} type="button" onClick={() => onSelect(a.language_code)}
          aria-current={a.language_code === current ? 'true' : undefined}
          className={`rounded-full px-3 py-1 font-medium transition ${a.language_code === current ? 'bg-brand-700 text-white' : 'bg-brand-50 text-brand-800 hover:bg-brand-100'}`}>
          {languageLabel(a.language_code)}
        </button>
      ))}
    </div>
  )
}
